export const glossaryById = new Map(glossary.map((t) => [t.id, t]))

/** Resolve a [[marker]]: explicit id, else the shown text as a slug, else that slug without a plural "s". */
export function resolveTerm(shown: string, id?: string): Term | undefined {
  if (id) return glossaryById.get(id)
  const slug = shown.toLowerCase().trim().replace(/\s+/g, '-')
  return glossaryById.get(slug) ?? glossaryById.get(slug.replace(/s$/, ''))
}

export const TERM_RE = /\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g

/** Every term a string marks, resolved; unknown markers come back as undefined so tests can catch them. */
export function termsIn(text: string): { shown: string; term: Term | undefined }[] {
  return [...text.matchAll(TERM_RE)].map((m) => ({ shown: m[1], term: resolveTerm(m[1], m[2]) }))
}

/** The text with markers reduced to their shown words. */
export function plainText(text: string): string {
  return text.replace(TERM_RE, (_, shown: string) => shown)
}
